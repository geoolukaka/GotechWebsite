#!/usr/bin/env python3
"""
GoTech portfolio terminal
=========================
Add, edit and remove projects on portfolio.html from your own terminal.

Run (from the website folder):
    python3 tools/portfolio.py            # opens the interactive terminal
    python3 tools/portfolio.py ls         # or run a single command

Needs only Python 3 (no installs). Project data lives in
assets/data/projects.json; this tool also regenerates assets/js/projects.js,
which is what portfolio.html actually loads.
"""
import cmd, json, re, shlex, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "assets/data/projects.json"
JS = ROOT / "assets/js/projects.js"
IMG_DIR = ROOT / "assets/images/portfolio"
CATS = ("brand", "software", "web")
IMG_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".svg"}


def load():
    return json.loads(DATA.read_text(encoding="utf-8")) if DATA.exists() else []


def save(projects):
    DATA.parent.mkdir(parents=True, exist_ok=True)
    DATA.write_text(json.dumps(projects, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    JS.parent.mkdir(parents=True, exist_ok=True)
    JS.write_text("/* Generated by tools/portfolio.py - do not edit by hand */\nwindow.PROJECTS = "
                  + json.dumps(projects, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def ask(label, default=""):
    shown = f" [{default}]" if default else ""
    v = input(f"  {label}{shown}: ").strip()
    return v if v else default


def find(projects, key):
    key = (key or "").lower().strip().rstrip("/")
    for p in projects:
        if p["k"] == key or p["n"].lower() == key:
            return p
    return None


def add_images(p, paths):
    dest = IMG_DIR / p["k"]
    dest.mkdir(parents=True, exist_ok=True)
    added = 0
    for raw in paths:
        src = Path(raw).expanduser()
        if not src.is_file() or src.suffix.lower() not in IMG_EXT:
            print(f"  ! skipped (not an image file): {raw}")
            continue
        name = slug(src.stem) + src.suffix.lower()
        n = 2
        while (dest / name).exists() and (dest / name).read_bytes() != src.read_bytes():
            name = f"{slug(src.stem)}-{n}{src.suffix.lower()}"
            n += 1
        shutil.copy2(src, dest / name)
        rel = f"assets/images/portfolio/{p['k']}/{name}"
        if rel not in p.setdefault("imgs", []):
            p["imgs"].append(rel)
            added += 1
    return added


def prompt_fields(p, projects, ask_name=True):
    if ask_name:
        p["n"] = ask("Name", p.get("n", "")) or p.get("n", "")
    cat = ""
    while cat not in CATS:
        cat = ask(f"Category ({'/'.join(CATS)})", p.get("c", "brand")).lower()
    p["c"] = cat
    tags = ask("Tags, comma separated", ", ".join(p.get("tg", [])))
    p["tg"] = [t.strip() for t in tags.split(",") if t.strip()]
    p["d"] = ask("Description", p.get("d", ""))
    link = ask("Live website link (blank = none, '-' = remove)", p.get("link", ""))
    if link == "-" or not link:
        p.pop("link", None)
    else:
        p["link"] = link if link.startswith("http") else "https://" + link
    cur_q = p.get("q")
    q = ask("Client quote (blank = none, '-' = remove)", cur_q[0] if cur_q else "")
    if q == "-" or not q:
        p.pop("q", None)
    else:
        who = ask("Quote credited to", cur_q[1] if cur_q else "")
        p["q"] = [q, who]


class Shell(cmd.Cmd):
    intro = "GoTech portfolio terminal. Type help, or exit to quit.\n"
    prompt = "gotech:$ "

    def emptyline(self):
        pass

    def default(self, line):
        print(f"command not found: {line.split()[0]}. try help")

    def do_help(self, _):
        print("""
  ls                      list projects (newest first)
  show <name>             show everything about one project
  add                     add a new project (guided prompts)
  edit <name>             change a project's details (Enter keeps current value)
  rm <name>               remove a project
  img <name> <files...>   add images to a project (drag files into the window)
  unimg <name> <number>   remove one image from a project
  top <name>              move a project to the top of the list
  preview                 view the site at http://localhost:8000
  publish ["message"]     git add + commit + push (GitHub Pages updates)
  exit                    quit
""")

    def do_ls(self, _):
        ps = load()
        if not ps:
            print("  (no projects yet - try: add)")
        for i, p in enumerate(ps, 1):
            print(f"  {i:>2}. {p['k']:<14} {p['c']:<9} {len(p.get('imgs', []))} img  {p['n']}")

    def do_show(self, a):
        p = find(load(), a)
        if not p:
            return print("  usage: show <name>   (see ls)")
        print(json.dumps(p, indent=2, ensure_ascii=False))

    def do_add(self, _):
        ps = load()
        p = {}
        name = ask("Name")
        if not name:
            return print("  cancelled")
        p["n"] = name
        k = slug(ask("Short key (used in the URL #key)", slug(name)))
        if find(ps, k):
            return print(f"  ! '{k}' already exists. Use: edit {k}")
        p["k"] = k
        prompt_fields(p, ps, ask_name=False)
        imgs = ask("Image files (separate with spaces, or blank)")
        if imgs:
            print(f"  {add_images(p, shlex.split(imgs))} image(s) added")
        ps.insert(0, p)
        save(ps)
        print(f"  added '{k}' at the top. Next: preview, then publish")

    def do_edit(self, a):
        ps = load()
        p = find(ps, a)
        if not p:
            return print("  usage: edit <name>   (see ls)")
        prompt_fields(p, ps)
        save(ps)
        print("  saved")

    def do_rm(self, a):
        ps = load()
        p = find(ps, a)
        if not p:
            return print("  usage: rm <name>   (see ls)")
        if input(f"  Delete '{p['n']}'? type yes: ").strip().lower() == "yes":
            ps.remove(p)
            save(ps)
            print("  removed (image files stay in assets/images/portfolio/)")

    def do_img(self, a):
        parts = shlex.split(a)
        ps = load()
        p = find(ps, parts[0]) if parts else None
        if not p or len(parts) < 2:
            return print("  usage: img <name> <file1> <file2> ...")
        n = add_images(p, parts[1:])
        save(ps)
        print(f"  {n} image(s) added to {p['k']}")

    def do_unimg(self, a):
        parts = a.split()
        ps = load()
        p = find(ps, parts[0]) if parts else None
        if not p or len(parts) < 2 or not parts[1].isdigit():
            return print("  usage: unimg <name> <number>   (numbers from: show <name>)")
        i = int(parts[1]) - 1
        if 0 <= i < len(p.get("imgs", [])):
            print("  removed", p["imgs"].pop(i))
            save(ps)
        else:
            print("  no image with that number")

    def do_top(self, a):
        ps = load()
        p = find(ps, a)
        if not p:
            return print("  usage: top <name>")
        ps.remove(p)
        ps.insert(0, p)
        save(ps)
        print("  moved to top")

    def do_preview(self, _):
        print("  Serving on http://localhost:8000  (Ctrl+C to stop)")
        try:
            subprocess.run([sys.executable, "-m", "http.server", "8000"], cwd=ROOT)
        except KeyboardInterrupt:
            print()

    def do_publish(self, a):
        msg = a.strip().strip('"') or "Update portfolio"
        if not (ROOT / ".git").exists():
            return print("  This folder isn't a git repo. Upload the changed files to GitHub\n"
                         "  (assets/data, assets/js/projects.js, assets/images/portfolio).")
        for c in (["git", "add", "-A"], ["git", "commit", "-m", msg], ["git", "push"]):
            if subprocess.run(c, cwd=ROOT).returncode != 0:
                return print("  ! stopped:", " ".join(c), "failed")
        print("  published - GitHub Pages updates in a minute or two")

    def do_exit(self, _):
        return True

    do_quit = do_exit
    do_EOF = do_exit


if __name__ == "__main__":
    sh = Shell()
    if len(sys.argv) > 1:
        sh.onecmd(" ".join(shlex.quote(x) for x in sys.argv[1:]))
    else:
        try:
            sh.cmdloop()
        except KeyboardInterrupt:
            print()
